"""Short, readable talent summaries for the site.

tools/summaries/<class>.json holds one template per talent, like "+{1}% Parry", where {1} is the first number
in that rank's game text. Numbers come from the live game data, so balance changes need no rewrite.
Each template also stores the sign of the text it was written for (the text with numbers blanked out).
When the wording changes in a patch, the sign no longer matches: the site falls back to the game text and the
talent is listed in data/changes/pending-summaries.json for the nightly check to rewrite.

  python3 tools/build_summaries.py           build classes/summaries/*.js and the pending list
  python3 tools/build_summaries.py --stamp   also record the current sign on templates that have none (after writing new ones)
"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'summaries')
DATA = os.path.join(ROOT, 'data', 'talentsforever')
OUT = os.path.join(ROOT, 'classes', 'summaries')
NUM = re.compile(r'\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?')

def sign(text):
    return re.sub(r'\s+', ' ', NUM.sub('#', text or '')).strip()

def fill(t, text):
    nums = NUM.findall(text or '')
    def sub(m):
        i = int(m.group(1)) - 1
        if i >= len(nums): raise IndexError
        return nums[i]
    return re.sub(r'\{(\d+)\}', sub, t)

def main(stamp):
    os.makedirs(OUT, exist_ok=True)
    pending, problems = [], []
    for f in sorted(os.listdir(SRC)):
        if not f.endswith('.json'): continue
        cls = f[:-5]
        src = json.load(open(os.path.join(SRC, f)))
        d = json.load(open(os.path.join(DATA, cls + '.json')))
        ranks = {x['name']: x.get('desc') or [] for t in d['talents']['trees'] for x in t['talents']}
        out, changed = {}, False
        for name, rk in ranks.items():
            e = src.get(name)
            if isinstance(e, str): e = src[name] = {'t': e}; changed = True
            cur = sign(rk[-1] if rk else '')
            if not e:
                pending.append({'class': cls, 'talent': name, 'why': 'no summary yet', 'text': rk}); continue
            if stamp and 'sig' not in e: e['sig'] = cur; changed = True
            if e.get('sig') != cur:
                pending.append({'class': cls, 'talent': name, 'why': 'game text changed', 'summary': e['t'], 'text': rk}); continue
            try:
                for r in rk: fill(e['t'], r)
            except IndexError:
                problems.append(f'{cls} {name}: template asks for a number the text does not have'); continue
            out[name] = e['t']
        for gone in [n for n in src if n not in ranks]:
            problems.append(f'{cls} {gone}: talent no longer in the game data')
        if changed:
            json.dump(src, open(os.path.join(SRC, f), 'w'), indent=1, ensure_ascii=False)
        js = ('/* Generated by tools/build_summaries.py from tools/summaries/%s.json. Do not edit by hand. */\n' % cls +
              '(window.FY_SUM ||= {}).%s = ' % cls + json.dumps({'talents': out}, ensure_ascii=False, separators=(',', ':')) + ';\n')
        open(os.path.join(OUT, cls + '.js'), 'w').write(js)
    os.makedirs(os.path.join(ROOT, 'data', 'changes'), exist_ok=True)
    json.dump({'pending': pending, 'problems': problems}, open(os.path.join(ROOT, 'data', 'changes', 'pending-summaries.json'), 'w'), indent=1, ensure_ascii=False)
    print(f'{len(pending)} pending, {len(problems)} problems')
    for p in problems: print(' ', p)

if __name__ == '__main__':
    main('--stamp' in sys.argv)
